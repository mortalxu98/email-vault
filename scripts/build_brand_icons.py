def logos_symbol(key: str, icons: dict, name: str) -> str:  # type: ignore[type-arg]
    icon = icons["icons"][name]
    width = icon.get("width", icons.get("width", 256))
    height = icon.get("height", icons.get("height", 256))
    body: str = icon["body"]
    # Prefix internal ids so gradients from different icons don't collide.
    for old in set(re.findall(r'id="([^"]+)"', body)):
        new = f"brand-{key}-{old}"
        body = (
            body.replace(f'id="{old}"', f'id="{new}"')
            .replace(f"url(#{old})", f"url(#{new})")
            .replace(f'href="#{old}"', f'href="#{new}"')
        )
    return f'<symbol id="brand-{key}" viewBox="0 0 {width} {height}">{body}</symbol>'


def si_symbol(key: str, pkg: Path, hexes: dict[str, str], slug: str) -> str:
    svg = (pkg / "icons" / f"{slug}.svg").read_text()
    match = re.search(r'<path d="([^"]+)"', svg)
    if match is None:
        raise ValueError(f"no path in {slug}.svg")
    return (
        f'<symbol id="brand-{key}" viewBox="0 0 24 24">'
        f'<path fill="#{hexes[slug]}" d="{match.group(1)}"/></symbol>'
    )


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    icons = json.loads(Path(sys.argv[1]).read_text())
    pkg = Path(sys.argv[2])
    data = json.loads((pkg / "data" / "simple-icons.json").read_text())
    hexes = {item["slug"]: item["hex"] for item in data}

    lines = [
        "{#- Generated by scripts/build_brand_icons.py. Sources (CC0): gilbarbara/logos",
        "    via @iconify-json/logos, and simple-icons. Trademarks belong to their owners. -#}",
    ]
    for key, (source, name) in SOURCES.items():
        if source == "logos":
            lines.append(logos_symbol(key, icons, name))
        else:
            lines.append(si_symbol(key, pkg, hexes, name))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(SOURCES)} symbols to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
